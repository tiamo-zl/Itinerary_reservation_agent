"""应用层依赖的协议。

应用服务只依赖这些 Protocol；SQLite 实现在 infra/repositories，
外部业务系统（审批、编排）也通过协议注入，便于单测替换。
"""

from __future__ import annotations

from collections.abc import AsyncIterator
from contextlib import AbstractAsyncContextManager
from typing import Protocol

from itinerary_agent.domain.models import Decision, Event, RequestContext


class TaskRepositoryPort(Protocol):
    async def get(self, task_id: str) -> dict | None: ...
    async def get_trace_id(self, task_id: str) -> str | None: ...
    async def find_by_trace(self, trace_id: str) -> dict | None: ...
    async def list_for_session(self, session_id: str) -> list[dict]: ...
    async def acquire_resume_lease(self, task_id: str, owner: str,
                                   lease_seconds: int) -> dict | None: ...
    async def release_lease(self, task_id: str, owner: str) -> None: ...
    async def upsert(self, task_id: str, tenant_id: str, user_id: str,
                     status: str, revision: int,
                     trace_id: str | None) -> None: ...
    async def set_status(self, task_id: str, status: str) -> None: ...


class TraceRepositoryPort(Protocol):
    async def load_spans(self, trace_id: str) -> list[dict]: ...
    async def load_flow_spans(self, trace_id: str) -> list[dict]: ...
    async def list_traces(self, limit: int,
                          tenant_id: str | None = None) -> list[dict]: ...
    async def list_task_summaries(self, limit: int,
                                  tenant_id: str | None = None) -> list[dict]: ...
    async def list_traces_for_task(self, task_id: str) -> list[dict]: ...
    async def overview_snapshot(self) -> dict: ...


class ConversationRepositoryPort(Protocol):
    async def list_conversations(self, admin: bool, user_id: str,
                                  tenant_id: str, limit: int) -> list[dict]: ...
    async def list_sessions(self, user_id: str, tenant_id: str,
                            limit: int) -> list[dict]: ...
    async def latest_task(self, session_id: str) -> dict | None: ...
    async def list_tasks(self, session_id: str) -> list[dict]: ...


class ApprovalRepositoryPort(Protocol):
    async def list_by_status(self, status: str, limit: int) -> list[dict]: ...
    async def get(self, approval_id: str) -> dict | None: ...
    async def list_for_task(self, task_id: str) -> list[dict]: ...


class FeedbackRepositoryPort(Protocol):
    async def create(self, badcase: dict) -> None: ...
    async def list_badcases(self, status: str | None,
                            limit: int) -> list[dict]: ...
    async def get(self, badcase_id: str) -> dict | None: ...
    async def update(self, badcase_id: str, changes: dict) -> None: ...


class OrchestrationPort(Protocol):
    """编排服务的读写接口；worker 通过 resume 继续 Checkpoint。"""

    async def get_state(self, task_id: str) -> dict: ...
    async def get_history(self, task_id: str, limit: int) -> list[dict]: ...
    async def get_messages(self, session_id: str,
                           limit: int = 100) -> list[dict]: ...
    def resume(self, ctx: RequestContext, task_id: str,
               decision: Decision) -> AsyncIterator[Event]: ...


class ApprovalSystemPort(Protocol):
    """外部审批系统；审批状态流转只经过这里。"""

    async def decide(self, approval_id: str, status: str,
                     comment: str) -> None: ...


class PingPort(Protocol):
    """就绪探针依赖的最小接口。"""

    async def ping(self) -> bool: ...


class UnitOfWorkPort(Protocol):
    """应用服务需要的事务边界；具体实现由 infra 注入。"""

    def transaction(self) -> AbstractAsyncContextManager[object]: ...


class OutboxRepositoryPort(Protocol):
    async def enqueue(self, aggregate_type: str, aggregate_id: str,
                      event_type: str, payload: dict) -> None: ...
    async def claim_batch(self, limit: int, worker_id: str,
                          lease_seconds: int) -> list[dict]: ...
    async def mark_done(self, event_id: int) -> None: ...
    async def mark_failed(self, event_id: int, error: str,
                          max_attempts: int) -> None: ...
